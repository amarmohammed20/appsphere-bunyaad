// Colours belong to the theme, not to a component. `text-zinc-900
// dark:text-zinc-100` hardcodes a decision twice; `text-foreground` states the
// role and lets `:root` and `.dark` decide. A client re-theme should be six CSS
// variables, not 178 class occurrences across 22 files.
//
// This exists because the migration that removed those 178 missed four, and
// nothing caught it. A rule this repo only documents is a rule it does not have.

import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const PALETTE =
  'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose';

const RAW_COLOUR = new RegExp(
  `\\b(?:dark:|hover:|focus:|focus-visible:|group-hover:|active:|disabled:)*(?:bg|text|border|ring|from|via|to|divide|outline|decoration|shadow|accent|caret|fill|stroke|placeholder)-(?:${PALETTE})-\\d{2,3}\\b`,
  'g',
);

// Generated by shadcn and regenerated on every `add`.
const IGNORED_PATHS = [/^src\/components\/ui\//];

// A deliberate exception must say so within the three lines above it — the same
// "comment or it is a mistake" rule used elsewhere.
const EXEMPTION = /Raw colours?:/i;

const files = execSync('git ls-files "src/**/*.tsx" "src/**/*.ts"', { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean)
  .filter((file) => !IGNORED_PATHS.some((pattern) => pattern.test(file)));

const violations = [];

for (const file of files) {
  const lines = readFileSync(file, 'utf8').split(/\r?\n/);

  lines.forEach((line, index) => {
    const matches = line.match(RAW_COLOUR);

    if (matches === null) {
      return;
    }

    const preceding = lines.slice(Math.max(0, index - 3), index).join('\n');

    if (EXEMPTION.test(preceding)) {
      return;
    }

    violations.push({ file, line: index + 1, classes: [...new Set(matches)].join(', ') });
  });
}

if (violations.length > 0) {
  console.error('::error::Raw palette colours found. Use semantic tokens instead:\n');

  for (const { file, line, classes } of violations) {
    console.error(`  ${file}:${line}  ${classes}`);
  }

  console.error('\n  text-zinc-900 dark:text-zinc-100  ->  text-foreground');
  console.error('  text-zinc-500 dark:text-zinc-400  ->  text-muted-foreground');
  console.error('  bg-zinc-50    dark:bg-zinc-950    ->  bg-background');
  console.error('  border-zinc-200 dark:border-zinc-800 -> border-border');
  console.error('  red-*                             ->  destructive');
  console.error('\nIf a raw colour is deliberate, say so in a comment on one of the');
  console.error('three lines above it, starting "Raw colours:".\n');
  process.exit(1);
}

console.warn(`No raw palette colours in ${files.length} files — every colour comes from a token.`);
